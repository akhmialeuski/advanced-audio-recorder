/**
 * Transcription provider abstraction. A provider turns one audio payload
 * into timed segments. The orchestrating service prepares the audio
 * (reading the file, optionally decoding and chunking) according to each
 * provider's declared capabilities, so providers only implement a single
 * request - keeping API, local, and future providers interchangeable.
 * @module transcription/providers/TranscriptionProvider
 */

import type { EngineLabel } from '../../providers/providers';
import type { TranscriptionProviderId } from '../../settings/settingsSchema';
import type { WhisperResult } from './whisperResponse';

/** Options for a single transcription call. */
export interface TranscribeOptions {
	/** Language hint (BCP-47/ISO), or undefined to auto-detect. */
	language?: string | undefined;
	/**
	 * Every language the recording switches between, when more than one is
	 * configured and the engine reads a list (see
	 * {@link ProviderCapabilities.readsLanguageList}). {@link language} then
	 * holds the first of them for whatever reads a single code.
	 */
	languages?: string[] | undefined;
	/** Request speaker diarization when the provider supports it. */
	diarize: boolean;
	/**
	 * Whether this run's output should carry per-word timing. Already gated by
	 * the engine's {@link ProviderCapabilities.wordTimestamps}, so a provider
	 * that cannot deliver it never sees a true here.
	 */
	wordTimestamps: boolean;
	/**
	 * Optional abort signal for the provider's HTTP requests. Providers on
	 * CORS-capable endpoints pass it through so a cancel aborts the upload
	 * mid-flight; providers that cannot abort (requestUrl-only endpoints,
	 * the local CLI) ignore it and remain cancel-between-chunks only.
	 */
	signal?: AbortSignal | undefined;
	/**
	 * Domain terms (names, abbreviations, jargon) to bias recognition toward,
	 * already parsed and de-duplicated. Each provider injects them the way its
	 * API supports: Deepgram keyterm/keywords, Whisper prompt, Gemini
	 * instruction text. Undefined or empty when the user set no dictionary or
	 * the engine cannot bias, so a provider sends nothing extra.
	 */
	dictionary?: string[] | undefined;
	/**
	 * Whisper-style initial prompt: one natural sentence in the audio language
	 * with the most valuable tokens last, generated by the advanced two-pass
	 * mode from the first pass's transcript. Engines that bias through prompt
	 * text (Whisper `prompt`, whisper.cpp `--prompt`, the Gemini instruction)
	 * send it instead of the comma-joined {@link dictionary} prompt - the
	 * sentence already folds the relevant terms in. Undefined outside the
	 * advanced second pass.
	 */
	biasPrompt?: string;
	/**
	 * Generated key terms for engines that bias through keyword lists
	 * (Deepgram keyterm/keywords), from the advanced two-pass mode. Sent ahead
	 * of the {@link dictionary} terms within the same per-model request
	 * limits, so the generated context wins when the combined list overflows.
	 * Undefined outside the advanced second pass.
	 */
	keyterms?: string[];
	/**
	 * Ask the engine to translate the speech into English as it transcribes,
	 * rather than writing it down in the language it was spoken in. Only ever
	 * true for an engine whose
	 * {@link ProviderCapabilities.supportsSpeechTranslation} says it has an
	 * operation for it.
	 */
	translateToEnglish?: boolean;
}

/**
 * One unit of audio handed to a provider for a single request. The
 * orchestrator either passes the whole original file (when the provider
 * accepts the container format and the file fits its limit) or a decoded
 * 16 kHz mono WAV chunk. Segment timings returned by the provider are
 * relative to this payload; the service re-bases them by `offsetSeconds`.
 *
 * The payload is always in a container the provider reads as it stands, and
 * it is lent rather than given: the service sends the same payload again after
 * a refusal it may get past, so a provider only reads the bytes and never
 * decodes, transfers or rewrites them. Turning a container into one the engine
 * reads is the service's job, done once per run before any request (see
 * {@link ProviderCapabilities.originalContainers}). It used to be done inside
 * two providers, from the bytes the service still held, and the browser's
 * decoder takes the buffer it is given - so the retry after a 503 sent Gemini
 * an empty WebM and the run reported a decode failure instead of the refusal.
 */
export interface AudioPayload {
	/**
	 * Encoded bytes to send (original container bytes, or a WAV chunk).
	 * Read-only to the provider, for the reason given on the interface.
	 */
	data: ArrayBuffer;
	/** MIME type of the bytes (e.g. 'audio/wav', 'audio/webm'). */
	contentType: string;
	/** Filename hint for multipart uploads. */
	filename: string;
	/** Offset of this payload from the start of the recording, in seconds. */
	offsetSeconds: number;
}

/**
 * How an engine carries biasing terms: a Whisper-style prompt sentence, or a
 * flat keyword list. A property of the engine's API, so it lives with the rest
 * of its capabilities rather than as a hard-coded id check at the call site.
 */
export const AdvancedBiasChannel = {
	/** A Whisper-style prompt sentence the terms are woven into. */
	Prompt: 'prompt',
	/** A flat keyword list sent alongside the audio. */
	Keyterm: 'keyterm',
} as const;

/** One biasing channel (derived from {@link AdvancedBiasChannel}). */
export type AdvancedBiasChannel =
	(typeof AdvancedBiasChannel)[keyof typeof AdvancedBiasChannel];

/**
 * What an engine does with a request for per-word timing.
 *
 * Three answers rather than two, because the engines give three. Whisper API
 * reads the request and adds the granularity to it. Deepgram returns per-word
 * timing on every response whether it was asked or not. Gemini and local
 * whisper.cpp return segment-level timing and nothing finer. A switch offered
 * on all four told the user nothing about which of those they would get.
 */
export const WordTimestampSupport = {
	/** The request carries the granularity and the engine honours it. */
	Requested: 'requested',
	/** Per-word timing comes back whether it was asked for or not. */
	Always: 'always',
	/** Segment-level timing only, with nothing finer available. */
	None: 'none',
} as const;

/** What an engine does with the request (derived from {@link WordTimestampSupport}). */
export type WordTimestampSupport =
	(typeof WordTimestampSupport)[keyof typeof WordTimestampSupport];

/** The two things that name the container a recording arrives in. */
export interface AudioContainer {
	/** MIME type declared for the bytes, e.g. 'audio/webm'. */
	readonly contentType: string;
	/** Lowercase file extension without its dot, '' when there is none. */
	readonly extension: string;
}

/**
 * Which original containers an engine reads as they stand.
 *
 * A question rather than a set, because the engines publish their lists in
 * different units and neither unit can state the other's list. Google documents
 * Gemini's File API by MIME type; Mistral documents Voxtral by file extension,
 * and this plugin's format registry maps two extensions (`m4a`, `mp4`) onto one
 * `audio/mp4`, so a MIME set claiming Mistral's list would also claim the
 * container it left out.
 *
 * It answers for the recording's own container only. A recording in any other
 * container is decoded to 16 kHz mono WAV, which every engine reads whatever
 * this says about a WAV file the user recorded (local whisper.cpp reads none
 * of them as they stand, because a user's WAV is rarely 16 kHz mono).
 */
export interface ContainerSupport {
	/**
	 * Whether the engine reads this container with no decode.
	 * @param container - The recording's container
	 * @returns True when the original bytes can be sent as they are
	 */
	accepts(container: AudioContainer): boolean;
	/**
	 * The containers {@link accepts} admits, in the words a refusal uses to tell
	 * the user what to record or convert to. Absent for an engine that reads
	 * every container, or none, where converting would not avoid the decode.
	 */
	readonly acceptedNames?: string;
}

/**
 * How a per-request duration cap is held against a recording the engine reads
 * as it stands, whose length is not known without decoding it.
 */
export const DurationCapCheck = {
	/**
	 * The file is sent whole only when its byte size proves it is within the
	 * cap (see `withinDurationCap`); any other is decoded, which measures it,
	 * and split at the cap. For a cap that is about how much one request can
	 * answer reliably, where sending too much fails the run.
	 */
	ProvenByBytes: 'proven-by-bytes',
	/**
	 * The file is sent whole whatever its length and the endpoint enforces
	 * the cap. For a cap so long that the byte proof would decode nearly every
	 * recording into a WAV several times its size - which is the whole-file
	 * upload the engine is chosen for. A recording that is decoded anyway is
	 * still split at the cap, since its length is then known exactly.
	 */
	LeftToEndpoint: 'left-to-endpoint',
} as const;

/** One way of holding the cap (derived from {@link DurationCapCheck}). */
export type DurationCapCheck =
	(typeof DurationCapCheck)[keyof typeof DurationCapCheck];

/**
 * What a provider can accept in a single request. The service uses these
 * to decide whether to send the original file untouched or to decode and
 * split it into chunks that stay within the provider's limit.
 */
export interface ProviderCapabilities {
	/**
	 * Maximum bytes the provider accepts in one request. Use
	 * Number.POSITIVE_INFINITY for an effectively unbounded local provider.
	 */
	maxRequestBytes: number;
	/**
	 * Longest recording, in seconds, the provider transcribes reliably in one
	 * request. A recording longer than this is decoded and split into parts
	 * even when its byte size fits {@link maxRequestBytes}, because inference
	 * time and the output transcript grow with audio duration, not bytes. Use
	 * Number.POSITIVE_INFINITY when the provider has no practical per-request
	 * duration limit (a whole-file API like Deepgram, or a local engine).
	 * {@link durationCapCheck} says how the cap is held against a container
	 * sent as it stands.
	 */
	maxRequestSeconds: number;
	/**
	 * How {@link maxRequestSeconds} is held against a recording sent in its own
	 * container. Irrelevant to an engine without a cap.
	 */
	durationCapCheck: DurationCapCheck;
	/**
	 * Which original containers the provider reads as they stand. Any other
	 * is decoded to 16 kHz mono WAV by the service before the provider sees it,
	 * so a provider never decodes anything itself.
	 */
	originalContainers: ContainerSupport;
	/**
	 * Whether the provider can return speaker labels at all. Gates the
	 * diarization UI and the diarize request: an engine that cannot diarize
	 * (OpenAI's Whisper, local whisper.cpp) must not offer an enabled toggle,
	 * since the request would be silently ignored and mislead the user.
	 */
	supportsDiarization: boolean;
	/**
	 * Whether the engine can bias recognition toward user-supplied terms
	 * (a custom dictionary). Gates the dictionary field the same way
	 * {@link supportsDiarization} gates the diarization toggle: an engine
	 * that cannot bias must not offer an enabled field, since the terms
	 * would be silently dropped and mislead the user.
	 */
	supportsDictionary: boolean;
	/**
	 * What the engine does with a request for per-word timing. Gates the
	 * word-timestamp switch the way {@link supportsDiarization} gates the
	 * diarization toggle: a switch that changes nothing on the chosen engine is
	 * offered disabled, with the engine's actual behaviour named beside it,
	 * rather than accepting a request the engine will drop.
	 */
	wordTimestamps: WordTimestampSupport;
	/**
	 * Which representation of the advanced mode's generated context this engine
	 * reads. The context pipeline builds only what the channel needs, so a
	 * keyword-biased engine never pays for a prompt sentence it would discard,
	 * and the second pass routes the context onto the matching request field.
	 */
	biasChannel: AdvancedBiasChannel;
	/**
	 * Whether the engine has an operation that translates the speech into
	 * English while transcribing it. Gates the offer the way
	 * {@link supportsDiarization} gates the diarization toggle: an engine with
	 * no such operation must not be asked for one.
	 */
	supportsSpeechTranslation: boolean;
	/**
	 * Whether the engine reads the configured language hint. Every engine did
	 * until Voxtral, whose `timestamp_granularities` is documented as
	 * incompatible with `language` - and since the granularity is what makes the
	 * response carry segments at all, it is the hint that has to go. Gates the
	 * language row the way {@link supportsDiarization} gates the diarization
	 * toggle: a value that cannot reach the request is never sent, and the row
	 * says so rather than looking as though it applied.
	 */
	readsLanguageHint: boolean;
	/**
	 * Whether the engine can be told every language a recording switches
	 * between and answer with the language of each segment. Only Gemini can,
	 * because its instruction and response schema are ours to write; every
	 * other request field takes one code, so those engines receive the first
	 * code of a configured list.
	 */
	readsLanguageList: boolean;
}

/** A provider that transcribes a single audio payload. */
export interface TranscriptionProvider {
	/**
	 * The engine this provider implements. Typed as the settings id rather
	 * than a bare string, so an implementation cannot claim an id the settings
	 * (and therefore the engine registry) do not know about.
	 */
	readonly id: TranscriptionProviderId;
	/** Human-readable label, one of the engine names. */
	readonly label: EngineLabel;
	/** Whether the provider makes network calls (affects availability). */
	readonly requiresNetwork: boolean;
	/** What the provider accepts in a single request. */
	readonly capabilities: ProviderCapabilities;
	/**
	 * Transcribes one audio payload.
	 * @param payload - The audio bytes and their metadata
	 * @param options - Transcription options
	 * @returns Language and timed segments for this payload
	 */
	transcribe(
		payload: AudioPayload,
		options: TranscribeOptions,
	): Promise<WhisperResult>;
}
